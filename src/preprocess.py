import numpy as np
import librosa
import torch
import torch.nn.functional as F

from config import (
    SR,
    N_FFT,
    HOP_LENGTH,
    N_MELS,
    IMAGE_SIZE
)


# ==================================================
# 오디오 파일을 Mel-spectrogram으로 변환하는 함수
# ==================================================
def audio_to_mel(path):

    # ----------------------------------------------
    # 1. 오디오 파일 읽기
    # ----------------------------------------------
    # path에 있는 음성 파일을 불러온다.
    #
    # y  : 실제 음성 데이터(파형)
    # sr : 실제 사용된 sampling rate
    #
    # sr=SR
    # → 우리가 config.py에서 정한 sampling rate 사용
    #
    # mono=True
    # → 스테레오라면 왼쪽/오른쪽을 합쳐서
    #    하나의 음성 채널로 만든다.
    y, sr = librosa.load(
        str(path),
        sr=SR,
        mono=True
    )


    # ----------------------------------------------
    # 2. 빈 오디오인지 확인
    # ----------------------------------------------
    # 음성 데이터의 길이가 0이면 오류 발생
    if len(y) == 0:
        raise ValueError(
            f"empty audio: {path}"
        )


    # ----------------------------------------------
    # 3. Mel-spectrogram 만들기
    # ----------------------------------------------
    #
    # 음성 파형
    #    ↓
    # Mel-spectrogram
    #
    mel = librosa.feature.melspectrogram(
        y=y,
        sr=SR,
        n_fft=N_FFT,
        hop_length=HOP_LENGTH,
        n_mels=N_MELS,
        power=2
    )


    # ----------------------------------------------
    # 4. 값을 dB 단위로 변환
    # ----------------------------------------------
    # 사람이 보기 좋은 음량 크기 형태로 변환
    mel = librosa.power_to_db(
        mel,
        ref=np.max
    )


    # ----------------------------------------------
    # 5. 0 ~ 1 사이로 정규화
    # ----------------------------------------------
    #
    # 가장 작은 값 → 0
    # 가장 큰 값   → 1
    #
    mel = (
        mel - mel.min()
    ) / (
        mel.max() - mel.min() + 1e-8
    )


    # ----------------------------------------------
    # 6. NumPy → PyTorch Tensor
    # ----------------------------------------------
    #
    # 현재:
    #     mel = [주파수, 시간]
    #
    # CNN은 보통:
    #     [채널, 높이, 너비]
    #
    # 그래서 차원을 추가한다.
    x = torch.tensor(
        mel,
        dtype=torch.float32
    )


    # ----------------------------------------------
    # 7. 채널 차원 추가
    # ----------------------------------------------
    #
    # [주파수, 시간]
    #       ↓
    # [1, 주파수, 시간]
    #
    # 1은 흑백 이미지처럼 채널이 1개라는 뜻
    x = x.unsqueeze(0)


    # ----------------------------------------------
    # 8. 배치 차원 추가
    # ----------------------------------------------
    #
    # [1, 주파수, 시간]
    #       ↓
    # [1, 1, 주파수, 시간]
    #
    # PyTorch 이미지 입력 형태:
    # [배치, 채널, 높이, 너비]
    x = x.unsqueeze(0)


    # ----------------------------------------------
    # 9. 크기를 IMAGE_SIZE에 맞게 변경
    # ----------------------------------------------
    #
    # Mel-spectrogram의 크기가
    # 파일마다 조금씩 다를 수 있기 때문에
    # 모델에 넣기 전에 동일한 크기로 맞춘다.
    x = F.interpolate(
        x,
        size=(N_MELS, IMAGE_SIZE),
        mode="bilinear",
        align_corners=False
    )


    # ----------------------------------------------
    # 10. 배치 차원 제거
    # ----------------------------------------------
    #
    # 현재:
    # [1, 1, N_MELS, IMAGE_SIZE]
    #
    # Dataset에서 하나의 데이터를 반환할 때는
    # 배치 차원이 필요 없으므로 제거한다.
    #
    # 결과:
    # [1, N_MELS, IMAGE_SIZE]
    x = x.squeeze(0)


    # ----------------------------------------------
    # 11. 완성된 Mel-spectrogram 반환
    # ----------------------------------------------
    return x